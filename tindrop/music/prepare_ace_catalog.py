#!/usr/bin/env python3
"""Prepare the Tindrop Originals generated locally with ACE-Step 1.5.

Reads `ace_tracks.json`, trims the silent tail of each lossless master, encodes
the mobile AAC candidate, delegates cue analysis to Tindrop's canonical Dart
analyzer and writes a catalog source containing only these tracks.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

from catalog_cue_analyzer import canonical_beat_map, preview_start


LICENSE_URL = "https://lagartijalabs.com/tindrop/music/licenses/originals.html"
MEDIA_ROOT = "https://media.lagartijalabs.com/tindrop/music/v1"
MOBILE_BITRATE = "128k"
TAIL_SILENCE_DB = -45
FADE_OUT_S = 1.2


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def probe_seconds(path: Path) -> float:
    result = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(path)],
        check=True, capture_output=True, text=True,
    )
    return float(result.stdout.strip())


def audible_end(path: Path) -> float:
    """End of the music: start of a silence that runs to the end of the file."""
    total = probe_seconds(path)
    result = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-af",
         f"silencedetect=n={TAIL_SILENCE_DB}dB:d=1", "-f", "null", "-"],
        check=True, capture_output=True, text=True,
    )
    starts = [float(v) for v in re.findall(r"silence_start: ([0-9.]+)", result.stderr)]
    ends = [float(v) for v in re.findall(r"silence_end: ([0-9.]+)", result.stderr)]
    if starts and (len(ends) < len(starts) or ends[-1] >= total - 0.05):
        return min(total, starts[-1] + 0.4)
    return total


def encode(source: Path, output: Path, title: str, artist: str) -> None:
    end = audible_end(source)
    fade_start = max(0.0, end - FADE_OUT_S)
    shape = f"atrim=0:{end:.3f},afade=t=out:st={fade_start:.3f}:d={FADE_OUT_S}"
    target = "I=-16:TP=-2:LRA=11"
    measured = subprocess.run(
        ["ffmpeg", "-hide_banner", "-nostats", "-i", str(source),
         "-af", f"{shape},loudnorm={target}:print_format=json", "-f", "null", "-"],
        check=True, capture_output=True, text=True,
    ).stderr
    stats = json.loads(measured[measured.rindex("{"):measured.rindex("}") + 1])
    # Linear two-pass gain keeps the mix dynamics; the limiter leaves headroom
    # for AAC inter-sample overshoot so decoded peaks stay below 0 dBFS.
    normalize = (
        f"loudnorm={target}:linear=true:measured_I={stats['input_i']}"
        f":measured_TP={stats['input_tp']}:measured_LRA={stats['input_lra']}"
        f":measured_thresh={stats['input_thresh']}:offset={stats['target_offset']}"
        ",alimiter=limit=0.63:level=false"
    )
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
         "-map_metadata", "-1",
         "-af", f"{shape},{normalize}",
         "-ar", "44100", "-ac", "2", "-c:a", "aac", "-profile:a", "aac_low",
         "-b:a", MOBILE_BITRATE, "-movflags", "+faststart",
         "-metadata", f"title={title}", "-metadata", f"artist={artist}", str(output)],
        check=True,
    )


def generation_record(source: Path) -> dict:
    manifest = json.loads((source.parent / "manifest.json").read_text(encoding="utf-8"))
    for track in manifest["tracks"]:
        if track["file"] == source.name:
            return track
    raise ValueError(f"{source}: missing from its generation manifest")


def write_evidence(root: Path, track: dict, artist: str, generator: str, record: dict, source_sha: str) -> None:
    (root / "licenses" / f"{track['id']}.md").write_text(
        f"# {track['title']}\n\n"
        f"- Artist: {artist} / Lagartija Labs\n"
        "- License ID in catalog: `proprietary`\n"
        f"- Genre label: {track['genre']}\n"
        f"- Provenance: generated locally by Lagartija Labs with {generator}. "
        "Model weights are MIT licensed; no third-party samples, melodies or artist references were used in the prompt.\n"
        f"- Prompt: {record['caption']}\n"
        f"- Requested BPM/key: {record.get('bpm')} / {record.get('key')}; seed `{record.get('seed')}`\n"
        f"- Lossless master: `{track['source']}` (SHA-256 `{source_sha}`), kept outside the CDN\n"
        "- Distribution grant: approved for use inside Tindrop exports and the public Tindrop music CDN.\n"
        "- Cue preparation: full-track `BeatMap` generated by Tindrop's canonical Dart analyzer, identical to imported user audio.\n",
        encoding="utf-8",
    )


def main() -> None:
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser()
    parser.add_argument("--tindrop-root", type=Path, required=True)
    parser.add_argument("--issued-at-ms", type=int, required=True)
    parser.add_argument("--version", type=int, required=True)
    parser.add_argument("--tracks", type=Path, default=root / "ace_tracks.json")
    parser.add_argument("--output", type=Path, default=root.parent.parent / ".artifacts" / "tindrop_music_ace_v1")
    parser.add_argument("--catalog", type=Path, default=root / "catalog.local.json")
    parser.add_argument("--reuse-encoded", action="store_true")
    args = parser.parse_args()

    spec = json.loads(args.tracks.read_text(encoding="utf-8"))
    source_root = Path(spec["sourceRoot"])
    args.output.mkdir(parents=True, exist_ok=True)
    catalog_tracks = []
    for index, track in enumerate(spec["tracks"]):
        artist = f"{track['genre']} · {spec['artist']}"
        source = source_root / track["source"]
        output = args.output / f"{track['id']}.m4a"
        if not args.reuse_encoded or not output.is_file():
            encode(source, output, track["title"], artist)
        duration_ms = round(probe_seconds(output) * 1000)
        record = generation_record(source)
        # The requested generation tempo resolves half/double-time ambiguity
        # (e.g. 76 vs 152 BPM); beats and drift still come from the audio.
        cues = canonical_beat_map(output, duration_ms, args.tindrop_root, record.get("bpm"))
        catalog_tracks.append({
            "id": track["id"],
            "title": track["title"],
            "artist": artist,
            "audioUrl": f"{MEDIA_ROOT}/{track['id']}.m4a",
            "durationMs": duration_ms,
            "sizeBytes": output.stat().st_size,
            "sha256": sha256(output),
            "licenseId": "proprietary",
            "licenseUrl": LICENSE_URL,
            "sortOrder": (index + 1) * 10,
            "previewStartMs": preview_start(cues, duration_ms),
            "featured": bool(track.get("featured", False)),
            "beatMap": cues,
        })
        write_evidence(root, track, spec["artist"], spec["generator"], record, sha256(source))
        print(f"prepared {output.name}: {duration_ms} ms, {cues.get('bpm', 0):.1f} BPM", flush=True)
    payload = {"version": args.version, "issuedAtMs": args.issued_at_ms, "tracks": catalog_tracks}
    args.catalog.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(args.catalog)


if __name__ == "__main__":
    main()
